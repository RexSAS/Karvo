import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.android)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.ksp)
}

val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}

android {
    namespace = "com.masterski"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.masterski"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
    }

    signingConfigs {
        if (keystorePropsFile.exists()) {
            create("release") {
                fun prop(key: String): String =
                    keystoreProps.getProperty(key)?.takeIf { it.isNotBlank() }
                        ?: throw GradleException("keystore.properties is missing '$key'")
                val path = prop("storeFile")
                val resolved = if (path.startsWith("~/")) {
                    file(System.getProperty("user.home") + path.removePrefix("~"))
                } else {
                    file(path)
                }
                if (!resolved.exists()) {
                    throw GradleException("keystore.properties: storeFile '$path' does not exist")
                }
                storeFile = resolved
                storePassword = prop("storePassword")
                keyAlias = prop("keyAlias")
                keyPassword = prop("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystorePropsFile.exists()) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    testOptions { unitTests.isIncludeAndroidResources = true }
}

